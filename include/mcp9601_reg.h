#ifndef MCP9601_REG_H
#define MCP9601_REG_H

// MCP960-1 Addresses
#define MCP9601_MIN_ADDR (0x60) //(0b11000001)
#define MCP9601_MAX_ADDR (0x67) //(0b11001111)
//#define MCP9601_ADDR_STEP (2)

#define MCP9601_TH_TEMP_REG 0x00  //((0b0000 << 4) || (0b0000))  // read only
#define MCP9601_TD_TEMP_REG 0x01 //((0b0000 << 4) || (0b0001))  // read only
#define MCP9601_TC_TEMP_REG 0x02 // ((0b0000 << 4) || (0b0010))  // read only
#define MCP9601_ADC_RAW_REG 0x03 //((0b0000 << 4) || (0b0011))  // read only
#define MCP9601_STATUS_REG 0x04 //((0b0000 << 4) || (0b0100))
#define MCP9601_THRMCPL_SNSR_CONFIG_REG 0x05 //((0b0000 << 4) || (0b0101))
#define MCP9601_DEV_CONFIG_REG 0x06//((0b0000 << 4) || (0b0110))
//#define MCP9601_ALRT_1_CONFIG_PTR ((0b0000 << 4) || (0b1000))
//#define MCP9601_ALRT_2_CONFIG_PTR ((0b0000 << 4) || (0b1001))
//#define MCP9601_ALRT3_CONFIG_PTR ((0b0000 << 4) || (0b1010))
//#define MCP9601_ALRT4_CONFIG_PTR ((0b0000 << 4) || (0b1011))
#define MCP9601_DEV_ID_REG 0x20 //((0b0010 << 4) || (0b0000))

#define MCP9601_ADCSPS_SELFHEAT_18B (float)(0.0096f)
#define MCP9601_ADCSPS_SELFHEAT_16B (float)(0.0384f)
#define MCP9601_ADCSPS_SELFHEAT_14B (float)(0.1536f)
#define MCP9601_ADCSPS_SELFHEAT_12B (float)(0.1920f)

// Device configuration setting bits
// Cold Junction Sensor Resolution
#define MCP9601_TC_RES_SET_BIT (7)
#define MCP9601_TC_RES_LOW_MASK (0b0 << MCP9601_TC_RES_SET_BIT)  // tc res at 0.25C
#define MCP9601_TC_RES_HIGH_MASK (0b1 << MCP9601_TC_RES_SET_BIT)  // tc res at 0.0625C
// ADC Measurement Resolution
#define MCP9601_ADC_RES_SET_BIT (6)
#define MCP9601_ADC_RES_18B_MASK (0b00 << MCP9601_ADC_RES_SET_BIT)
#define MCP9601_ADC_RES_16B_MASK (0b01 << MCP9601_ADC_RES_SET_BIT)
#define MCP9601_ADC_RES_14B_MASK (0b10 << MCP9601_ADC_RES_SET_BIT)
#define MCP9601_ADC_RES_12B_MASK (0b11 << MCP9601_ADC_RES_SET_BIT)
// Burst mode sample count
#define MCP9601_BRST_MODE_SET_BIT (4)
#define MCP9601_BRST_CNT_1_MASK (0b000 << MCP9601_BRST_MODE_SET_BIT)
#define MCP9601_BRST_CNT_2_MASK (0b001 << MCP9601_BRST_MODE_SET_BIT)
#define MCP9601_BRST_CNT_4_MASK (0b010 << MCP9601_BRST_MODE_SET_BIT)
#define MCP9601_BRST_CNT_8_MASK (0b011 << MCP9601_BRST_MODE_SET_BIT)
#define MCP9601_BRST_CNT_16_MASK (0b100 << MCP9601_BRST_MODE_SET_BIT)
#define MCP9601_BRST_CNT_32_MASK (0b101 << MCP9601_BRST_MODE_SET_BIT)
#define MCP9601_BRST_CNT_64_MASK (0b110 << MCP9601_BRST_MODE_SET_BIT)
#define MCP9601_BRST_CNT_128_MASK (0b111 << MCP9601_BRST_MODE_SET_BIT)
// Shutdown Modes
#define MCP9601_SHTDWN_SET_BIT (1)
#define MCP9601_SHTDWN_NRML_MODE_MASK (0b00 << MCP9601_SHTDWN_SET_BIT)
#define MCP9601_SHTDWN_SHTDWN_MODE_MASK (0b01 << MCP9601_SHTDWN_SET_BIT)
#define MCP9601_SHTDWN_BRST_MODE_MASK (0b10 << MCP9601_SHTDWN_SET_BIT)
//#define MCP9601_SHTDWN_UIMPL_MASK (0b11 << MCP9601_SHTDWN_SET_BIT)

// Thermocouple Sensor configuration
// Thermocouple Type K
#define MCP9601_THRMCPL_TYPE_SET_BIT (6)
#define MCP9601_THRMCPL_TYPE_K_MASK (0b000 << MCP9601_THRMCPL_TYPE_SET_BIT)
#define MCP9601_THRMCPL_TYPE_J_MASK (0b001 << MCP9601_THRMCPL_TYPE_SET_BIT)
#define MCP9601_THRMCPL_TYPE_T_MASK (0b010 << MCP9601_THRMCPL_TYPE_SET_BIT)
#define MCP9601_THRMCPL_TYPE_N_MASK (0b011 << MCP9601_THRMCPL_TYPE_SET_BIT)
#define MCP9601_THRMCPL_TYPE_S_MASK (0b100 << MCP9601_THRMCPL_TYPE_SET_BIT)
#define MCP9601_THRMCPL_TYPE_E_MASK (0b101 << MCP9601_THRMCPL_TYPE_SET_BIT)
#define MCP9601_THRMCPL_TYPE_B_MASK (0b110 << MCP9601_THRMCPL_TYPE_SET_BIT)
#define MCP9601_THRMCPL_TYPE_R_MASK (0b111 << MCP9601_THRMCPL_TYPE_SET_BIT)
// Filter Coefficients
#define MCP9601_THRMCPL_FLTR_SET_BIT (2)
#define MCP9601_THRMCPL_FLTR_N_0_MASK (0b000 << MCP9601_THRMCPL_FLTR_SET_BIT) // filter off
#define MCP9601_THRMCPL_FLTR_N_1_MASK (0b001 << MCP9601_THRMCPL_FLTR_SET_BIT) // min filter
#define MCP9601_THRMCPL_FLTR_N_2_MASK (0b010 << MCP9601_THRMCPL_FLTR_SET_BIT) 
#define MCP9601_THRMCPL_FLTR_N_3_MASK (0b011 << MCP9601_THRMCPL_FLTR_SET_BIT)
#define MCP9601_THRMCPL_FLTR_N_4_MASK (0b100 << MCP9601_THRMCPL_FLTR_SET_BIT) // mid filter
#define MCP9601_THRMCPL_FLTR_N_5_MASK (0b101 << MCP9601_THRMCPL_FLTR_SET_BIT)
#define MCP9601_THRMCPL_FLTR_N_6_MASK (0b110 << MCP9601_THRMCPL_FLTR_SET_BIT)
#define MCP9601_THRMCPL_FLTR_N_7_MASK (0b111 << MCP9601_THRMCPL_FLTR_SET_BIT) // max filter

// Status Register
#define MCP9601_STATUS_BRST_CMPLT_BIT (7)
#define MCP9601_STATUS_TH_UPDT_BIT (6)
#define MCP9601_STATUS_SHRT_CRKT_BIT (5)
#define MCP9601_STATUS_INP_RNG_BIT (4)
#define MCP9601_STATUS_ALRT_4_BIT (3)
#define MCP9601_STATUS_ALRT_3_BIT (2)
#define MCP9601_STATUS_ALRT_2_BIT (1)
#define MCP9601_STATUS_ALRT_1_BIT (0)

#endif
